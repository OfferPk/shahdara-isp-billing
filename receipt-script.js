/**
 * receipt-script.js — Plan 168: Payment receipt in Urdu script option.
 *
 * A print-time rendering option for the existing payment receipt. The
 * operator chooses the script when printing; nothing is stored, no
 * receipt record is created or altered, and no bill, payment, or total
 * ever changes. The stored receipt's own facts — customer name, amount,
 * date, and month — render byte-identical in both scripts; only the
 * field labels change from their Roman/bilingual form to Urdu script.
 *
 * Fence: SISP-91 (receipt-preferences.js) already stores a per-customer
 * receipt language preference that drives the WhatsApp/PNG slips. This
 * module is deliberately separate: it carries no customer record and no
 * stored preference, and it touches only the printed receipt HTML
 * produced by generatePaymentReceiptHtml. A receipt without a script
 * choice prints exactly as before.
 *
 * Pure and import-free: no DOM, no storage, no mutation. applyReceiptScript
 * takes rendered HTML and returns a new string; the input is never changed.
 */

export const RECEIPT_SCRIPTS = ['roman', 'urdu'];

/**
 * The script to render a receipt in, or null when unset/corrupt.
 * Unset (null) means "print as before" — the Roman/bilingual layout.
 */
export function sanitizeReceiptScript(value) {
  const cleaned = typeof value === 'string' ? value.trim().toLowerCase() : '';
  return cleaned === 'urdu' || cleaned === 'roman' ? cleaned : null;
}

/** Human label for a script choice, for panel text. */
export function receiptScriptLabel(script) {
  return sanitizeReceiptScript(script) === 'urdu' ? 'Urdu script' : 'Roman Urdu';
}

